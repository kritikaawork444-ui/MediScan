export function t(key, lang) {
  const code = lang || getLanguage() || "en";
  const pack = DICT[code] || DICT.en;
  return pack[key] ?? DICT.en[key] ?? key;
}

export function setLanguage(code) {
  persistLanguage(code);
  try {
    window.dispatchEvent(new CustomEvent("mediscan:language", { detail: { code } }));
  } catch {
    /* ignore */
  }
}

